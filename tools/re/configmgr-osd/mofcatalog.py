"""Summarize the SMS_TaskSequence_* classes in ConfigMgr's _TaskSequenceProvider.mof.

Usage: python -I mofcatalog.py <mof> > catalog.md

Writes two Markdown tables: each step class with the CommandLine qualifier that
names the executable it runs, and each class property with its type, default
value and VariableName qualifier (the task sequence variable it sets).
"""
import re
import sys

text = open(sys.argv[1], encoding="utf-8", errors="replace").read().replace("\r", "")
# strip // comments
text = re.sub(r"//[^\n]*", "", text)

cls_re = re.compile(
    r"(?:\[((?:[^\[\]]|\[[^\]]*\])*)\]\s*)?class\s+(SMS_TaskSequence_\w+)\s*(?::\s*(\w+))?\s*\{(.*?)\n\};", re.S
)
steps = []
for m in cls_re.finditer(text):
    quals, name = m.group(1) or "", m.group(2)
    cmd = re.search(r'CommandLine\(\s*((?:"(?:[^"\\]|\\.)*"\s*)+)\)', quals)
    if cmd:
        cmd = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', cmd.group(1))).replace("\\\\", "\\")
    if name.endswith("Action") or cmd:
        steps.append((name, cmd or ""))
print("# Task sequence step catalog\n")
print("Generated by `tools/re/configmgr-osd/mofcatalog.py` from ConfigMgr's")
print("`SMSSETUP/BIN/X64/_TaskSequenceProvider.mof`. An empty variable column means the")
print("property has no `VariableName` qualifier. The step can still read a variable by")
print("convention: Upgrade Operating System reads `OSDUpgrade<Property>`, for example.\n")
print("## Steps and the executable each one runs\n")
print("| Class | Command line |")
print("|---|---|")
for name, cmd in steps:
    print(f"| {name} | `{cmd}` |" if cmd else f"| {name} | |")
print("\n## Properties and the task sequence variables they set\n")
prop_re = re.compile(
    r"(\[[^\]]*\])?\s*(boolean|string|uint32|uint64|sint32|datetime|uint8|object)\s*(\[\])?\s+(\w+)\s*(?:=\s*([^;]+))?;",
    re.S,
)

print("| Class | Base | Property | Type | Default | TS variable |")
print("|---|---|---|---|---|---|")
for m in cls_re.finditer(text):
    name, base, body = m.group(2), m.group(3) or "", m.group(4)
    for p in prop_re.finditer(body):
        quals, typ, arr, prop, default = p.groups()
        quals = quals or ""
        var = re.search(r'VariableName\("([^"]+)"\)', quals)
        default = (default or "").strip().replace("|", "\\|")
        default = re.sub(r"\s+", " ", default)
        if len(default) > 90:
            default = default[:87] + "..."
        print(f"| {name} | {base} | {prop} | {typ}{'[]' if arr else ''} | {default} | {var.group(1) if var else ''} |")
